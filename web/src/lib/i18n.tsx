const DICTS: Record<Lang, Dict> = { vi, en };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: string, v?: Record<string, string | number>) => string; L: (o: any) => string };
const LangContext = createContext<Ctx>(null as any);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = local.get<Lang | null>('sy_lang', null);
    if (saved && LANGS.includes(saved)) return saved;
    const nav = (typeof navigator !== 'undefined' ? navigator.language : 'vi').slice(0, 2);
    return (LANGS.includes(nav as Lang) ? nav : 'vi') as Lang;
  });
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const value = useMemo<Ctx>(() => ({
    lang,
    setLang: l => { local.set('sy_lang', l); setLangState(l); },
    t: (k, v) => { let s = DICTS[lang][k] ?? vi[k] ?? k; if (v) for (const [a, b] of Object.entries(v)) s = s.split('{' + a + '}').join(String(b)); return s; },
    L: o => (o && typeof o === 'object' ? (o[lang] || o.vi || o.en || '') : String(o ?? ''))
  }), [lang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}
export const useI18n = () => useContext(LangContext);
